from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np


PROJECT_DIR = Path(__file__).resolve().parent.parent
MODELS_DIR = PROJECT_DIR / "Models"
DEFAULT_OUTPUT_PATH = MODELS_DIR / "charge_dataset.npz"

EPSILON_0 = 1.0
GRID_SIZE = 32
GRID_MIN = -2.0
GRID_MAX = 2.0
CHARGE_COUNT = 2
DEFAULT_SAMPLE_COUNT = 10_000
DEFAULT_G05_POINT_COUNT = 32
DEFAULT_DATASET_SEED = 20_260_821

TARGET_FIELDS = ("x1", "y1", "z1", "q1", "x2", "y2", "z2", "q2")
G05_FIELDS = ("grid_x_index", "grid_y_index", "signed_potential")


def coulomb_potential(
    observation_x: np.ndarray,
    observation_y: np.ndarray,
    charge_x: np.ndarray,
    charge_y: np.ndarray,
    charge_z: np.ndarray,
    charge_q: np.ndarray,
) -> np.ndarray:
    """Return the z=0 potential generated by all charges."""
    distance = np.sqrt(
        (observation_x[..., np.newaxis] - charge_x) ** 2
        + (observation_y[..., np.newaxis] - charge_y) ** 2
        + charge_z**2
    )
    return np.sum(
        charge_q / (4.0 * np.pi * EPSILON_0 * distance),
        axis=-1,
    )


def create_spatially_balanced_sensor_order(
    grid_size: int,
    point_count: int,
    seed: int,
) -> np.ndarray:
    """Create a deterministic nested maximin ordering of grid cells.

    Each prefix is a spatially dispersed sensor set. This makes the lower G05
    fractions strict subsets of the higher fractions without changing which
    samples receive measurements.
    """
    cell_count = grid_size * grid_size
    if not 1 <= point_count <= cell_count:
        raise ValueError(
            f"point_count must be in [1, {cell_count}], received {point_count}"
        )

    y_index, x_index = np.indices((grid_size, grid_size))
    coordinates = np.column_stack((x_index.ravel(), y_index.ravel()))
    permutation = np.random.default_rng(seed).permutation(cell_count)
    candidates = coordinates[permutation]

    selected_indices = np.empty(point_count, dtype=np.int64)
    selected_indices[0] = 0
    minimum_distance_squared = np.sum(
        (candidates - candidates[0]) ** 2,
        axis=1,
    ).astype(np.float64)

    for point_index in range(1, point_count):
        next_index = int(np.argmax(minimum_distance_squared))
        selected_indices[point_index] = next_index
        distance_squared = np.sum(
            (candidates - candidates[next_index]) ** 2,
            axis=1,
        )
        minimum_distance_squared = np.minimum(
            minimum_distance_squared,
            distance_squared,
        )

    return candidates[selected_indices].astype(np.int64)


def generate_dataset(
    sample_count: int = DEFAULT_SAMPLE_COUNT,
    g05_point_count: int = DEFAULT_G05_POINT_COUNT,
    seed: int = DEFAULT_DATASET_SEED,
) -> dict[str, np.ndarray]:
    """Generate G00, multi-point G05, and explicitly documented targets."""
    if sample_count < 1:
        raise ValueError("sample_count must be positive")
    if g05_point_count < 10:
        raise ValueError(
            "g05_point_count must be at least 10 so a 10% condition is meaningful"
        )

    rng = np.random.default_rng(seed)
    grid_axis = np.linspace(GRID_MIN, GRID_MAX, GRID_SIZE, dtype=np.float64)
    grid_x, grid_y = np.meshgrid(grid_axis, grid_axis)
    sensor_indices = create_spatially_balanced_sensor_order(
        GRID_SIZE,
        g05_point_count,
        seed + 1,
    )
    sensor_x = grid_axis[sensor_indices[:, 0]]
    sensor_y = grid_axis[sensor_indices[:, 1]]

    dataset_g00 = np.empty(
        (sample_count, GRID_SIZE, GRID_SIZE),
        dtype=np.float32,
    )
    dataset_g05 = np.empty(
        (sample_count, g05_point_count, len(G05_FIELDS)),
        dtype=np.float32,
    )
    dataset_target = np.empty(
        (sample_count, len(TARGET_FIELDS)),
        dtype=np.float32,
    )

    for sample_index in range(sample_count):
        charge_position = np.column_stack(
            (
                rng.uniform(-1.5, 1.5, CHARGE_COUNT),
                rng.uniform(-1.5, 1.5, CHARGE_COUNT),
                rng.uniform(0.1, 1.5, CHARGE_COUNT),
            )
        )
        charge_value = (
            rng.choice(np.array([-1.0, 1.0]), CHARGE_COUNT)
            * rng.uniform(0.3, 1.0, CHARGE_COUNT)
        )

        # The target label is deterministic under charge permutation.
        order = np.lexsort(
            (
                charge_position[:, 2],
                charge_position[:, 1],
                charge_position[:, 0],
            )
        )
        charge_position = charge_position[order]
        charge_value = charge_value[order]

        full_potential = coulomb_potential(
            grid_x,
            grid_y,
            charge_position[:, 0],
            charge_position[:, 1],
            charge_position[:, 2],
            charge_value,
        )
        sensor_potential = coulomb_potential(
            sensor_x,
            sensor_y,
            charge_position[:, 0],
            charge_position[:, 1],
            charge_position[:, 2],
            charge_value,
        )

        dataset_g00[sample_index] = full_potential**2
        dataset_g05[sample_index, :, 0:2] = sensor_indices
        dataset_g05[sample_index, :, 2] = sensor_potential
        dataset_target[sample_index] = np.column_stack(
            (charge_position, charge_value)
        ).ravel()

    return {
        "G00": dataset_g00,
        "G05": dataset_g05,
        "target": dataset_target,
        "target_fields": np.asarray(TARGET_FIELDS),
        "g05_fields": np.asarray(G05_FIELDS),
        "sensor_grid_indices": sensor_indices,
        "grid_x": grid_axis,
        "grid_y": grid_axis,
        "epsilon_0": np.asarray(EPSILON_0),
        "generation_seed": np.asarray(seed, dtype=np.int64),
        "partial_g05_definition": np.asarray(
            "fixed spatially-balanced nested sensor prefixes"
        ),
    }


def save_dataset(dataset: dict[str, np.ndarray], output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(output_path, **dataset)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate the two-charge G00/G05 inverse-problem dataset."
    )
    parser.add_argument("--samples", type=int, default=DEFAULT_SAMPLE_COUNT)
    parser.add_argument("--g05-points", type=int, default=DEFAULT_G05_POINT_COUNT)
    parser.add_argument("--seed", type=int, default=DEFAULT_DATASET_SEED)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    dataset = generate_dataset(
        sample_count=args.samples,
        g05_point_count=args.g05_points,
        seed=args.seed,
    )
    save_dataset(dataset, args.output)
    print("Dataset:", args.output.resolve())
    print("G00:", dataset["G00"].shape)
    print("G05:", dataset["G05"].shape)
    print("target:", dataset["target"].shape)
    print("target fields:", tuple(dataset["target_fields"]))


if __name__ == "__main__":
    main()
